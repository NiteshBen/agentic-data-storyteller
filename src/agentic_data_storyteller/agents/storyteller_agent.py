from typing import Dict, Any, List
from ..models.schema import DatasetProfile, InsightReport, StoryOutput
from ..utils.llm_bridge import LLMBridge

class StorytellerAgent:
    """
    Autonomous agent that translates statistical findings and charts
    into an executive markdown report and ready-to-publish LinkedIn post.
    """

    def __init__(self, name: str = "StorytellerAgent", llm_bridge: LLMBridge = None):
        self.name = name
        self.llm = llm_bridge or LLMBridge()

    def generate_stories(
        self,
        profile: DatasetProfile,
        insights: InsightReport,
        dashboard_path: str,
        infographic_path: str,
        repo_url: str = "https://github.com/NiteshBen/agentic-data-storyteller"
    ) -> StoryOutput:
        
        # 1. Prepare Executive Report
        top_drivers_text = "\n".join([
            f"- **{d['feature_a']} ↔ {d['feature_b']}**: correlation of `{d['correlation']:.2f}` ({d['direction']})"
            for d in insights.key_drivers[:5]
        ]) or "- No strong pairwise linear correlations detected above threshold."

        core_findings_text = "\n".join([
            f"### {idx+1}. {item.title}\n{item.description}\n"
            for idx, item in enumerate(insights.insights[:4])
        ])

        exec_story = f"""# Executive Data Intelligence Briefing

**Generated by**: Autonomous Agentic Data Storyteller  
**Lead Author / Developer**: Nitesh Beniwal  
**Repository**: [{repo_url}]({repo_url})  

---

## 1. Executive Summary
{insights.summary}

### Key Dataset Dimensions
- **Total Records Analyzed**: {profile.row_count:,}
- **Features Scanned**: {profile.column_count} ({len(profile.numeric_columns)} numeric, {len(profile.categorical_columns)} categorical, {len(profile.datetime_columns)} temporal)
- **High-Leverage Anomaly Count**: {sum(profile.outliers_iqr.values()):,} records flagged across dimensions.

---

## 2. Key Business Drivers & Correlations
{top_drivers_text}

---

## 3. Core Insights & Anomaly Analysis
{core_findings_text}

---

## 4. Strategic Recommendations
1. **Capitalize on Categorical Concentration**: Optimize acquisition and supply channels around identified leading categories to maximize volume efficiency.
2. **Investigate High-Variance Outliers**: Isolate high-leverage anomaly clusters to extract best practices and prevent revenue leakage.
3. **Continuous Metric Monitoring**: Implement real-time alerting on top correlation pairs to identify macro-trend shifts early.

---

## 5. Artifacts & Deliverables
- **Interactive Dashboard**: `{dashboard_path}`
- **Executive Infographic Vector**: `{infographic_path}`
"""

        # 2. Prepare LinkedIn Post
        first_insight = insights.insights[0].description if insights.insights else "Significant variance and category concentration uncovered."
        driver_highlight = f"{insights.key_drivers[0]['feature_a']} strongly aligns with {insights.key_drivers[0]['feature_b']} (r = {insights.key_drivers[0]['correlation']:.2f})" if insights.key_drivers else "Uncovered high-leverage operational drivers"

        linkedin_post = f"""🚀 Built & Launched: **Agentic Data Storyteller** — An Autonomous Multi-Agent BI & Executive Narrative Engine! 📊🤖

In today's data-driven world, dashboards alone aren't enough. Decision-makers need **context, key drivers, and clear executive stories**.

I built an end-to-end multi-agent system in Python that takes any raw tabular dataset, statistically profiles it, and automatically generates:
1️⃣ Deep statistical profiling & outlier detection (IQR)
2️⃣ Correlation & driver discovery
3️⃣ Interactive glassmorphic HTML dashboards (Plotly)
4️⃣ High-resolution executive infographic cards (SVG)
5️⃣ Complete executive briefing & strategic recommendations

🔍 **Key Highlights from the Latest Run**:
• Scanned **{profile.row_count:,} records** across **{profile.column_count} dimensions**
• **Top Driver Identified**: {driver_highlight}
• **Primary Finding**: {first_insight}

💡 **Tech Stack**:
Python 3 | Pandas | NumPy | Plotly | Google GenAI (Gemini) | Multi-Agent Orchestration | SVG Generation

🔗 **Explore the open-source GitHub repository**:
👉 {repo_url}

I’d love to hear your thoughts on how multi-agent workflows are reshaping business intelligence! 💬

#DataScience #Python #ArtificialIntelligence #MachineLearning #BusinessIntelligence #Analytics #PowerBI #DataAnalytics #OpenSource #PortfolioProject #AI #Automation #AgenticAI #GenAI
"""

        return StoryOutput(
            executive_summary=insights.summary,
            executive_story_markdown=exec_story,
            linkedin_post=linkedin_post,
            html_dashboard_path=dashboard_path,
            infographic_svg_path=infographic_path,
            key_metrics={
                "records": profile.row_count,
                "columns": profile.column_count,
                "drivers_count": len(insights.key_drivers),
                "insights_count": len(insights.insights)
            }
        )
